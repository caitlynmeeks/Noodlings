#   This folder contains the neural network architectures that
#   make Noodlings tick. There are several "phases" of increasing
#   complexity:
#
#   Phase 1-2: Basic hierarchical processing (fast/medium/slow layers)
#   Phase 3: Episodic memory and attention ("remembering")
#   Phase 4: Social cognition ("what is the other person feeling?")
#   Phase 6: Appetites and goals ("what do I want?")
#
#   There are also experimental quantum-inspired layers that add
#   randomness in interesting ways, and observer loops that create
#   self-referential dynamics.
